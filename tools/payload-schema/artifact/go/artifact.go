// Package artifact makes the pinned bootstrap artifact of a payload schema
// (docs/contribution-contract.md, row 38, O9, O39): from the schema source, a
// horos module, it makes the canonical module, its pin and the file that
// states the pin. It is the public route from a schema source to the pinned
// artifact: a contribution that is authored outside this repository makes its
// artifact through this package or through the command beside it, and needs
// no internal package of bittype.
//
// The artifact of one payload schema is five files in the vocabulary package
// of its contribution:
//
//	payload.horos      the schema source, written by hand
//	payload.ontos      its canonical module (Module)
//	payload_schema.go  the pin of that module (PinFile)
//	payload_types.go   the plain Go type of the payload
//	and, in the codec package, the hand-written codec
package artifact

import (
	"context"
	"errors"
	"fmt"

	parsecontract "github.com/Bitspark/bittype/contracts/parse/go"
	"github.com/Bitspark/bittype/internal/horosmodel"
	horosparse "github.com/Bitspark/bittype/parse/syntax/horos/provider/go"
	"github.com/Bitspark/bittype/transform/syntax/horos/payload/go"
	codec "github.com/bitspark/ontos/codec/go"
)

// Names of the files of an artifact.
const (
	SourceFile = "payload.horos"
	ModuleFile = "payload.ontos"
	PinFile    = "payload_schema.go"
	TypesFile  = "payload_types.go"
)

// Module lowers a schema source to its canonical module and returns the
// module with its pin. The source is one horos module.
func Module(ctx context.Context, source string) (module []byte, pin string, err error) {
	tree, err := horosparse.Parse(ctx, parsecontract.Input{SourceID: SourceFile, TreeID: "module", Text: source})
	if err != nil {
		return nil, "", err
	}
	modules, err := horosmodel.SourceModules(tree.Abstract)
	if err != nil {
		return nil, "", err
	}
	if len(modules) != 1 {
		return nil, "", errors.New("a payload schema source is exactly one module")
	}
	module = codec.Encode(modules[0].Value)
	pin, err = payload.Pin(module)
	return module, pin, err
}

// Pin returns the Go file that states the pin of a schema module, for the
// vocabulary package named pkg.
func Pin(pkg, pin string) string {
	return fmt.Sprintf("// Code generated by bittype's payload-schema tool from %s. DO NOT EDIT.\n\npackage %s\n\n// SchemaPin is the pin of the canonical schema module.\nconst SchemaPin = %q\n", SourceFile, pkg, pin)
}
