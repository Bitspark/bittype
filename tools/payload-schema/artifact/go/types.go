// TypesHeader is the first line of a generated types file.
const TypesHeader = "// Code generated by bittype from " + SourceFile + ". DO NOT EDIT."

// Types generates the plain Go types of a payload schema, as the file
// payload_types.go of the vocabulary package named pkg. bittype generates them
// itself: the schema source goes through the horos frontend and through
// generation with bittype's own structural Go contributions, each registered
// with the codec of its payload schema. So a payload type is what the
// structural profile gives for its schema, and nothing is written by hand.
//
// A schema may use what those contributions cover: text, booleans, lists,
// closed records with required and optional fields, and named declarations.
// A field that they cannot type is refused here as generation refuses it.
func Types(ctx context.Context, schemaSource, pkg string) (string, error) {
	if pkg == "" {
		return "", errors.New("a types file needs the name of its package")
	}
	tree, err := horosparse.Parse(ctx, parsecontract.Input{SourceID: SourceFile, TreeID: "module", Text: schemaSource})
	if err != nil {
		return "", err
	}
	modules, err := horosmodel.SourceModules(tree.Abstract)
	if err != nil {
		return "", err
	}
	if len(modules) != 1 {
		return "", errors.New("a payload schema source is exactly one module")
	}
	canonical, err := resolve.Resolve(modules[0].Value, nil, "canonical")
	if err != nil {
		return "", err
	}
	from, err := representation.NewLanguage[h.Language](h.Language{}, h.Profile)
	if err != nil {
		return "", err
	}
	to, err := representation.NewLanguage[gs.Language](gs.Language{}, "payload-types-v1")
	if err != nil {
		return "", err
	}
	e := engine.New()
	sourceChecker, err := check.NewChecker[h.Language](from, checkhoros.Provider{})
	if err != nil {
		return "", err
	}
	targetChecker, err := check.NewChecker[gs.Language](to, checkgolang.Provider{})
	if err != nil {
		return "", err
	}
	resolver, err := resolution.NewResolver[h.Language](from, horos.ResolutionContract(), resolve.Provider{})
	if err != nil {
		return "", err
	}
	analyzer, err := analysis.NewAnalyzer[h.Language](from, horos.AnalysisContract(), analyze.Provider{})
	if err != nil {
		return "", err
	}
	for _, register := range []func() error{
		func() error { return e.RegisterLanguage(from) },
		func() error { return e.RegisterLanguage(to) },
		func() error { return e.RegisterChecker(sourceChecker) },
		func() error { return e.RegisterChecker(targetChecker) },
		func() error { return e.RegisterResolver(resolver) },
		func() error { return e.RegisterAnalyzer(analyzer) },
	} {
		if err := register(); err != nil {
			return "", err
		}
	}
	envelope, err := representation.Pack(from, canonical)
	if err != nil {
		return "", err
	}
	snapshot, err := e.Capture(ctx, semantic.Input{Entry: ast.NodeRef{Tree: canonical.ID, Node: canonical.Root}, Trees: []representation.AST{envelope}})
	if err != nil {
		return "", err
	}
	resolved, err := e.Resolve(ctx, snapshot, semantic.Options{})
	if err != nil {
		return "", err
	}
	analyzed, err := e.Analyze(ctx, analysis.Input{Snapshot: snapshot, Resolution: &resolved})
	if err != nil {
		return "", err
	}
	input := transform.Input{Source: snapshot, Evidence: []semantic.Result{analyzed}}

	registry := e.Generation()
	if err := c.RegisterSource[h.Language, source.Reader](registry, from, source.Provider{}); err != nil {
		return "", err
	}
	if err := c.RegisterTarget(registry, to, target.Provider{Package: pkg}); err != nil {
		return "", err
	}
	type bundle struct {
		contribution func(representation.Language) (g.Contribution[h.Language, gs.Language, source.Reader], error)
		codec        func() (g.PayloadCodec, error)
	}
	for _, b := range []bundle{
		{text.Contribution, textcodec.Codec}, {boolean.Contribution, booleancodec.Codec}, {list.Contribution, listcodec.Codec},
		{record.Contribution, recordcodec.Codec}, {declarations.Contribution, declarationscodec.Codec}, {optional.Contribution, optionalcodec.Codec},
	} {
		contribution, err := b.contribution(from)
		if err != nil {
			return "", err
		}
		if err := c.RegisterContribution(registry, from, to, contribution); err != nil {
			return "", err
		}
		payloadCodec, err := b.codec()
		if err != nil {
			return "", err
		}
		if err := registry.RegisterCodec(payloadCodec); err != nil {
			return "", err
		}
	}
	roots, err := typeDefinitions(canonical)
	if err != nil {
		return "", err
	}
	out, err := e.Generate(ctx, c.Request{Input: input, To: to, Output: "payload-types", Roots: roots, Profile: rules.RepresentationProfile, Limits: g.DefaultLimits()})
	if err != nil {
		return "", err
	}
	entry, err := out.Snapshot().EntryTree()
	if err != nil {
		return "", err
	}
	generated, err := representation.Unpack[gs.Language](out.Snapshot().Language(), entry)
	if err != nil {
		return "", err
	}
	concrete, err := formatgolang.Provider{}.Format(ctx, generated)
	if err != nil {
		return "", err
	}
	printer, err := printing.New[gs.Language](gs.Language{})
	if err != nil {
		return "", err
	}
	printed, err := printer.Print(ctx, concrete)
	if err != nil {
		return "", err
	}
	// The printed unit begins with its package clause. The file states before
	// it that it is generated.
	clause := "package " + pkg
	if !strings.HasPrefix(printed, clause) {
		return "", errors.New("the generated unit does not begin with its package clause")
	}
	formatted, err := format.Source([]byte(TypesHeader + "\n\n" + printed))
	if err != nil {
		return "", err
	}
	return string(formatted), nil
}

// typeDefinitions are the roots of a schema: every type definition of its
// module, in the order of the source.
func typeDefinitions(tree h.AST) ([]ast.NodeRef, error) {
	var root ast.NodeRef
	for _, r := range tree.Nodes[tree.Root-1].References {
		if r.Role == h.RoleRoot {
			root = r.Target
		}
	}
	if root.Tree != tree.ID || root.Node == 0 || int(root.Node) > len(tree.Nodes) {
		return nil, errors.New("the schema module has no root")
	}
	var out []ast.NodeRef
	for _, child := range tree.Nodes[root.Node-1].Children {
		if tree.Nodes[child.Node-1].Kind == h.KindTypeDefinition {
			out = append(out, ast.NodeRef{Tree: tree.ID, Node: child.Node})
		}
	}
	if len(out) == 0 {
		return nil, errors.New("the schema module declares no type")
	}
	return out, nil
}
